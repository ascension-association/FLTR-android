#!/usr/bin/env python3
"""Generate the app's vector drawables from branding/fltr-astronaut.svg.

The official logo is an Inkscape export whose paths sit inside
transform="matrix(1.333,0,0,-1.333,0,H)" and transform="scale(0.1)" groups.
VectorDrawable groups support scale + translate, which is all those need,
so path data is copied through untouched.

Outputs (under app/src/main/res/drawable):
  fltr_astronaut.xml           full-colour logo, used in the app
  ic_launcher_foreground.xml   logo (no TM) inside the adaptive-icon safe zone
  ic_launcher_monochrome.xml   outline-only logo for Android 13+ themed icons

Run from the repository root:  python3 tools/svg2vector.py
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "branding" / "fltr-astronaut.svg"
OUT = ROOT / "app" / "src" / "main" / "res" / "drawable"
NS = "{http://www.w3.org/2000/svg}"

# Colours that make up the line art; the themed icon keeps only these.
OUTLINE = {"#371a45", "#220f2d"}


def load():
    root = ET.parse(SRC).getroot()
    w = float(root.get("width"))
    h = float(root.get("height"))
    paths = []
    for p in root.iter(NS + "path"):
        fill = re.search(r"fill:(#[0-9a-fA-F]{6})", p.get("style", "")).group(1).lower()
        d = " ".join(p.get("d").split())
        paths.append((d, fill))
    return w, h, paths


def is_trademark(d):
    # The two "TM" glyph paths sit in the bottom-right corner of the inner
    # coordinate space (x > 4000, y < 300); the laptop screen also starts at
    # x > 4000 but much higher up.
    m = re.match(r"[mM]\s*([0-9.]+),([0-9.]+)", d)
    return m is not None and float(m.group(1)) > 4000 and float(m.group(2)) < 300


def emit(name, size_dp, viewport, paths, *, scale, tx, ty, color=None):
    vw, vh = viewport
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/svg2vector.py from branding/fltr-astronaut.svg. Do not edit. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{size_dp[0]}dp"',
        f'    android:height="{size_dp[1]}dp"',
        f'    android:viewportWidth="{vw:g}"',
        f'    android:viewportHeight="{vh:g}">',
        f'  <group android:translateX="{tx:.4f}" android:translateY="{ty:.4f}"',
        f'      android:scaleX="{scale:.6f}" android:scaleY="{-scale:.6f}">',
    ]
    for d, fill in paths:
        lines.append(f'    <path android:fillColor="{color or fill.upper()}"')
        lines.append(f'        android:pathData="{d}" />')
    lines += ["  </group>", "</vector>", ""]
    (OUT / name).write_text("\n".join(lines))
    print("wrote", OUT / name, f"({len(paths)} paths)")


def main():
    w, h, paths = load()
    OUT.mkdir(parents=True, exist_ok=True)
    # Combined SVG transform: x' = 0.13333*x, y' = h - 0.13333*y.
    k = 1.3333333 * 0.1

    # 1. Full logo at its own aspect ratio.
    emit("fltr_astronaut.xml", (round(w / 2), round(h / 2)), (w, h), paths,
         scale=k, tx=0, ty=h)

    # 2. Adaptive icon: 108x108 viewport, artwork fitted into a 60 unit square
    #    so its corners stay inside the 66dp safe circle, centred.
    art = [(d, f) for d, f in paths if not is_trademark(d)]
    box = 60.0
    s = box / max(w, h)
    ox = (108 - w * s) / 2
    oy = (108 - h * s) / 2
    emit("ic_launcher_foreground.xml", (108, 108), (108, 108), art,
         scale=k * s, tx=ox, ty=oy + h * s)

    # 3. Monochrome: outline paths only, single colour (tinted by the launcher).
    mono = [(d, f) for d, f in art if f in OUTLINE]
    emit("ic_launcher_monochrome.xml", (108, 108), (108, 108), mono,
         scale=k * s, tx=ox, ty=oy + h * s, color="#FF000000")


if __name__ == "__main__":
    sys.exit(main())
